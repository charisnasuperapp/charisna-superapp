import {readFile, writeFile} from 'node:fs/promises';

// Deliberately enumerate UI assets. Never glob directories, fixtures, or environment files.
const files = [
  './overview.html',
  './overview.mjs',
  '../public/styles.css',
  './login.html',
  './login.mjs'
];
const cloud = new URL('../cloud/', import.meta.url);
const assets = Object.fromEntries(await Promise.all(files.map(async file => [file, await readFile(new URL(file, cloud), 'utf8')])));
const output = `// Generated by scripts/build-worker.mjs. Do not edit. Contains UI sources only.\nexport const assets = Object.freeze(${JSON.stringify(assets, null, 2)});\n\nexport function loadAsset(file) {\n  if (!Object.hasOwn(assets, file)) throw new Error('Unknown embedded asset');\n  return assets[file];\n}\n`;
await writeFile(new URL('assets.mjs', cloud), output, 'utf8');
console.log(`Embedded ${files.length} UI assets (${Buffer.byteLength(output)} bytes).`);
